#!/usr/bin/env bash
# 10-create-strata-lxc.sh - create the Strata container (CT 121) on prox-2.
#
# GPU access is device-node sharing, not VFIO: the host keeps amdgpu loaded.
# Thread placement: Strata pins one worker per physical core and skips the host
# core. Do NOT raise --pool-workers above the physical core count (13 on this
# 14-core Xeon): Strata issue #3417 measured 27.9 vs 38.1 tok/s with too many
# workers. The systemd unit below sets STRATA_AUX_CPUS=auto so helper threads
# use the idle SMT siblings.
set -euo pipefail

CTID="${CTID:-121}"
CT_HOSTNAME="${CT_HOSTNAME:-strata-2}"
STORAGE="${STORAGE:-nvme}"
TEMPLATE_STORAGE="${TEMPLATE_STORAGE:-local}"
ROOTFS_GB="${ROOTFS_GB:-380}"
MEMORY_MB="${MEMORY_MB:-57344}"   # 56 GiB
SWAP_MB="${SWAP_MB:-4096}"
CORES="${CORES:-28}"              # all threads; Strata self-pins workers to physical cores
BRIDGE="${BRIDGE:-vmbr0}"
RUN_SCRIPT="${RUN_SCRIPT:-run-iq3_s.sh}"  # generated by ./setup.sh for the chosen model
AUTO_SETUP="${AUTO_SETUP:-1}"
RENDER_NODE=/dev/dri/renderD128

[ "$(id -u)" -eq 0 ] || { echo "run as root on the Proxmox host"; exit 1; }
command -v pct >/dev/null || { echo "pct not found - is this the Proxmox host?"; exit 1; }

say() { printf '\n== %s ==\n' "$*"; }

say "Templates"
TEMPLATE=$(ls -1 /var/lib/vz/template/cache/debian-13-standard_*_amd64.tar.* 2>/dev/null | head -1 || true)
if [ -z "$TEMPLATE" ]; then
  echo "downloading Debian 13 template..."
  pveam update >/dev/null
  AVAIL=$(pveam available --section system | awk '/debian-13-standard/{print $2; exit}')
  [ -n "$AVAIL" ] || { echo "could not find debian-13 template in pveam"; exit 1; }
  pveam download "$TEMPLATE_STORAGE" "$AVAIL"
  TEMPLATE="/var/lib/vz/template/cache/$AVAIL"
else
  echo "using $TEMPLATE"
fi
VZTMPL="${TEMPLATE_STORAGE}:vztmpl/$(basename "$TEMPLATE")"

say "Container $CTID ($CT_HOSTNAME)"
if pct status "$CTID" >/dev/null 2>&1; then
  echo "CT $CTID already exists, leaving creation alone"
else
  pct create "$CTID" "$VZTMPL" \
    --hostname "$CT_HOSTNAME" \
    --unprivileged 1 \
    --features "fuse=1,nesting=1" \
    --rootfs "${STORAGE}:${ROOTFS_GB}" \
    --memory "$MEMORY_MB" \
    --swap "$SWAP_MB" \
    --cores "$CORES" \
    --net0 "name=eth0,bridge=${BRIDGE},ip=dhcp" \
    --onboot 1 \
    --description "Strata HIP engine. GPU shared from host via /dev/kfd + /dev/dri, no VFIO."
  echo "created CT $CTID"
fi

# ROCm pins host memory; lift the container's memlock rlimit (no-op if present)
grep -q '^lxc.prlimit.memlock' "/etc/pve/lxc/$CTID.conf" 2>/dev/null \
  || echo 'lxc.prlimit.memlock: unlimited' >>"/etc/pve/lxc/$CTID.conf"

say "GPU device nodes"
# GIDs are resolved inside the container: PVE writes the container-side owner.
echo "starting container once to read its render/video GIDs..."
pct start "$CTID" 2>/dev/null || true
for _ in $(seq 1 20); do pct exec "$CTID" -- true >/dev/null 2>&1 && break; sleep 1; done
RENDER_GID=$(pct exec "$CTID" -- getent group render | cut -d: -f3 || true)
RENDER_GID=${RENDER_GID:-992}
echo "container render GID: $RENDER_GID"

pct stop "$CTID"
# Only the ROCm compute nodes. Do NOT pass cardN: it renumbers across boots
# (card0 here, card1 after a cold boot) and a stale entry stops the CT start.
pct set "$CTID" \
  --dev0 "/dev/kfd,gid=${RENDER_GID}" \
  --dev1 "/dev/dri/renderD128,gid=${RENDER_GID}"
pct start "$CTID"
for _ in $(seq 1 20); do pct exec "$CTID" -- true >/dev/null 2>&1 && break; sleep 1; done

pct exec "$CTID" -- bash -c 'ls -l /dev/kfd /dev/dri/'
if pct exec "$CTID" -- test -r /dev/kfd && pct exec "$CTID" -- test -w /dev/dri/renderD128; then
  echo "device nodes readable/writable inside CT $CTID"
else
  echo "WARNING: device permission check failed; inspect the dev entries in /etc/pve/lxc/$CTID.conf" >&2
fi

say "Packages and Strata source"
pct exec "$CTID" -- bash -c '
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -qq
  apt-get install -y -qq git build-essential curl ca-certificates tmux python3 python3-venv python3-pip pkg-config procps >/dev/null
'
if ! pct exec "$CTID" -- test -d /opt/Strata/.git; then
  pct exec "$CTID" -- git clone --depth 1 https://github.com/Niko1221/Strata /opt/Strata
else
  echo "/opt/Strata already present"
fi

say "systemd unit (disabled until Strata setup has run)"
UNIT_TMP=$(mktemp)
cat >"$UNIT_TMP" <<'UNIT'
[Unit]
Description=Strata HIP inference engine (AMD GPU)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
WorkingDirectory=/opt/Strata
# run-*.sh is created by ./setup.sh after picking the model.
Environment=STRATA_AUX_CPUS=auto
# ROCm pinned host allocations for the expert arena.
LimitMEMLOCK=infinity
# Keep worker count automatic: one per physical core, never SMT siblings.
ExecStart=/bin/bash -lc 'exec ./@RUN_SCRIPT@'
Restart=on-failure
RestartSec=10
TimeoutStopSec=180

[Install]
WantedBy=multi-user.target
UNIT
# The unit is intentionally model-agnostic; substitute the run script name.
sed -i "s|@RUN_SCRIPT@|$RUN_SCRIPT|g" "$UNIT_TMP"
pct push "$CTID" "$UNIT_TMP" /etc/systemd/system/strata.service
rm -f "$UNIT_TMP"
pct exec "$CTID" -- systemctl daemon-reload
echo "unit written; enable after setup: systemctl enable --now strata"

say "Strata interactive setup"
if [ "$AUTO_SETUP" = "1" ]; then
  pct exec "$CTID" -- bash -c 'tmux has-session -t strata-setup 2>/dev/null || tmux new-session -d -s strata-setup "cd /opt/Strata && ./setup.sh --backend hip; echo; echo Setup finished. Press Enter to close.; read"'
  echo "setup started in tmux session 'strata-setup'"
else
  echo "AUTO_SETUP=0: run the setup yourself"
fi

cat <<EOF

Next steps:
  pct enter $CTID
  tmux attach -t strata-setup        # if AUTO_SETUP=1

  In setup choose the model and quantization that fit your RAM and VRAM.
  Reference choices: HIP backend, IQ3_S (ISTA-DASLab), 8-bit KV, images on
  with the CPU encoder, low-RAM mode. Model download is ~84 GB on the NVMe.
  When setup finishes, confirm the run script name (${RUN_SCRIPT}) and re-add
  --host 0.0.0.0 --port 8080 if setup regenerated it.
    systemctl cat strata
    systemctl enable --now strata

Verify from the host:
  bash 20-verify-strata.sh

CT rootfs is on fast NVMe. Resource limits in use: ${MEMORY_MB} MiB RAM, ${SWAP_MB} MiB swap, ${CORES} cores.
EOF
